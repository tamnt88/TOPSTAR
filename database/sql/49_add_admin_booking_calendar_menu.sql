SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRY
 BEGIN TRANSACTION;
 IF NOT EXISTS(SELECT 1 FROM dbo.Menus WHERE Code='MENU_ADMIN_BOOKING_CALENDAR') INSERT dbo.Menus(Id,Code,Title,Path,Icon,ParentId,OrderNo,IsVisible,CreatedAtUtc) VALUES(NEWID(),'MENU_ADMIN_BOOKING_CALENDAR',N'Lịch booking','/Admin/Calendar','fa-solid fa-calendar-days',NULL,8,1,SYSUTCDATETIME());
 DECLARE @roleId UNIQUEIDENTIFIER=(SELECT TOP 1 Id FROM dbo.Roles WHERE UPPER(Code)='ADMIN'),@menuId UNIQUEIDENTIFIER=(SELECT TOP 1 Id FROM dbo.Menus WHERE Code='MENU_ADMIN_BOOKING_CALENDAR');
 IF @roleId IS NOT NULL AND @menuId IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.RoleMenus WHERE RoleId=@roleId AND MenuId=@menuId) INSERT dbo.RoleMenus(RoleId,MenuId,CreatedAtUtc) VALUES(@roleId,@menuId,SYSUTCDATETIME());
 COMMIT TRANSACTION;
END TRY
BEGIN CATCH
 IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
 THROW;
END CATCH;
