SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF NOT EXISTS(SELECT 1 FROM dbo.Menus WHERE Code='MENU_ADMIN_OPERATIONS')
 INSERT INTO dbo.Menus(Id,Code,Title,Path,Icon,ParentId,OrderNo,IsVisible,CreatedAtUtc) VALUES(NEWID(),'MENU_ADMIN_OPERATIONS',N'Vận hành ngoại lệ','/Admin/Operations','fa-solid fa-triangle-exclamation',NULL,7,1,SYSUTCDATETIME());
DECLARE @Role UNIQUEIDENTIFIER=(SELECT TOP 1 Id FROM dbo.Roles WHERE UPPER(Code)='ADMIN');
DECLARE @Menu UNIQUEIDENTIFIER=(SELECT TOP 1 Id FROM dbo.Menus WHERE Code='MENU_ADMIN_OPERATIONS');
IF @Role IS NOT NULL AND @Menu IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.RoleMenus WHERE RoleId=@Role AND MenuId=@Menu)
 INSERT INTO dbo.RoleMenus(RoleId,MenuId,CreatedAtUtc) VALUES(@Role,@Menu,SYSUTCDATETIME());
COMMIT TRANSACTION;
